"""Writes the trained target network and its normalisation as a TypeScript
module the engine can run (adds, multiplies and comparisons only).

    python tools/nn-nation/export_weights.py
Reads .nn-nation-data/train/{target.pt,norm.npz}; writes
packages/engine/src/execution/utils/AttackNetWeights.ts.
"""
import os
import sys

import numpy as np
import torch

sys.path.insert(0, os.path.dirname(__file__))
import nn_data as D  # noqa: E402

OUT_TS = os.path.join(
    "packages", "engine", "src", "execution", "utils", "AttackNetWeights.ts"
)


def arr(a) -> str:
    """Nested lists of the float32 values as exact doubles."""
    a = np.asarray(a, np.float32)
    if a.ndim == 0:
        return repr(float(a))
    return "[" + ",".join(arr(x) for x in a) + "]"


def main() -> None:
    d = os.path.join(D.ROOT, "train")
    ck = torch.load(os.path.join(d, "target.pt"))
    sd = {k: v.numpy() for k, v in ck["state"].items()}
    z = np.load(os.path.join(d, "norm.npz"))
    ns = sd["ss.weight"].shape[1]
    nc = sd["cs.weight"].shape[1]
    fields = {
        "selfMean": z["self_mean"],
        "selfInvStd": z["self_inv_std"],
        "candMean": z["cand_mean"],
        "candInvStd": z["cand_inv_std"],
        "cs": sd["cs.weight"],
        "ss": sd["ss.weight"],
        "b1": sd["ss.bias"],
        "w2": sd["l2.weight"],
        "b2": sd["l2.bias"],
        "w3": sd["l3.weight"][0],
        "b3": sd["l3.bias"][0],
        "n1": sd["n1.weight"],
        "nb1": sd["n1.bias"],
        "n2": sd["n2.weight"][0],
        "nb2": sd["n2.bias"][0],
    }
    lines = [
        "// GENERATED by tools/nn-nation/export_weights.py from the trained target",
        "// network (.nn-nation-data/train). Do not edit by hand.",
        "// Each number is a float32 written as its exact shortest double; ESLint's",
        "// precision check is stricter than round-tripping, hence the disable.",
        "/* eslint-disable no-loss-of-precision */",
        'import type { AttackNetWeights } from "./AttackNet";',
        "",
        "export const ATTACK_NET_WEIGHTS: AttackNetWeights = {",
        f"  ns: {ns},",
        f"  nc: {nc},",
        f"  h1: {ck['h1']},",
        f"  h2: {ck['h2']},",
        f"  h3: {ck['h3']},",
    ]
    for k, v in fields.items():
        lines.append(f"  {k}: {arr(v)},")
    lines.append("};")
    with open(OUT_TS, "w", encoding="utf8") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", OUT_TS, f"(ns={ns} nc={nc} h1={ck['h1']} h2={ck['h2']} h3={ck['h3']})")


if __name__ == "__main__":
    main()
